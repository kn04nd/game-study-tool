READ_ONLY_OK = [
    "gst recon --deep", "gst status --short", "gst doctor --brief", "gst tools list", "gst.exe recon",
    "& 'C:/Users/x/.local/bin/gst.exe' recon", "ls -la recon/", "rg -n Player decomp/ | head -20",
    "cat recon/RECON.md", "Get-ChildItem -Recurse D:/game-study/oni/recon | Select-Object -First 5",
    "cd D:/game-study/oni && gst recon", "find . -name '*.pdb'", "diec -j -d Game.exe 2>&1", "rg x 2>/dev/null",
    "Get-Content recon/recon.json 2>$null",
]
READ_ONLY_DENIED = [
    "gst new oni", "gst tools install core", "gst config set gs_home D:/x", "rm -rf recon", "Remove-Item recon",
    "echo x > notes/a.md", "cat a >> b", "rg x | tee out.txt", "Get-Content a | Out-File b",
    "ls $(rm -rf x)", "ls `rm x`", "find . -name x -delete", "find . -exec rm {} ;", "python -c 'x'",
    "ls; curl http://example.com", "gst recon && git commit -m x", "FOO=1 ls",
]


@pytest.mark.parametrize("command", READ_ONLY_OK)
def test_read_only_agent_allows_listing_and_recon(command):
    assert guard.check_command(command, agent_type="gst:recon").allowed


@pytest.mark.parametrize("command", READ_ONLY_DENIED)
def test_read_only_agent_denies_everything_else(command):
    decision = guard.check_command(command, agent_type="gst:recon")
    assert not decision.allowed
    assert guard.check_command(command, agent_type="gst:code-navigator").allowed or decision.rule


