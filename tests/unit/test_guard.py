import pytest

from gst import guard, policy
from gst.common import is_under, norm_path


def test_norm_path_variants():
    assert norm_path(r"D:\SteamLibrary\steamapps") == "d:/steamlibrary/steamapps"
    assert norm_path("/d/SteamLibrary/steamapps/") == "d:/steamlibrary/steamapps"
    assert norm_path("//?/D:/x") == "d:/x"
    assert is_under(r"D:\game-study\oni\notes\a.md", "D:/game-study")
    assert not is_under("D:/game-study-old/x", "D:/game-study")


def test_git_root_detection(git_repo, tmp_path):
    assert guard.git_root(git_repo / "a" / "b.txt") == git_repo
    assert guard.git_root(tmp_path / "elsewhere" / "c.txt") is None


def test_write_decompiled_into_git_is_denied(git_repo):
    ghidra = "\n".join(f"undefined8 FUN_14000{i:04x}(void) {{ return DAT_14010{i:04x}; }}" for i in range(6))
    d = guard.check_write(git_repo / "src" / "game.c", ghidra)
    assert not d.allowed and d.rule == 7
    d = guard.check_write(git_repo / "decomp" / "Player.cs", "class Player {}")
    assert not d.allowed
    assert not guard.check_write(git_repo / "data" / "Hero.uasset", "x").allowed
    assert guard.check_write(git_repo / "src" / "tool.py", "print('hi')").allowed


def test_docs_that_name_decompilers_are_not_decompiled_output(git_repo):
    doc = "# Unity\n\nIL2CPP: Cpp2IL or Il2CppInspectorRedux (`process <in> -o <dir>`), then Ghidra.\n"
    assert guard.check_write(git_repo / "docs" / "unity.md", doc).allowed
    header = "// Generated by Il2CppInspector - https://github.com/djkaty\n\nnamespace Game {}\n"
    assert not guard.check_write(git_repo / "src" / "Types.cs", header).allowed


