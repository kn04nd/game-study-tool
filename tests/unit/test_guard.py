def test_extractors_that_write_into_the_current_folder(tmp_path):
    install = "C:/Program Files (x86)/Steam/steamapps/common/Dying Light"
    ws = tmp_path / "ws"
    rpack = f'RP6_UnpackCLI.exe "{install}/DW/Data0.rpack"'
    assert guard.check_command(rpack, cwd=ws).allowed  # reads the install, writes into the workspace
    assert guard.check_command(rpack, cwd=install).rule == 5
    assert guard.check_command(f'cd "{install}" && RP6_UnpackCLI DW/Data0.rpack', cwd=ws).rule == 5
    assert guard.check_command("Set-Location -Path 'C:/XboxGames/X/Content'; filediver -T unit", cwd=ws).rule == 5
    assert guard.check_command("filediver -T unit", cwd=install).rule == 5
    assert guard.check_command(f'filediver -o "{ws}/assets/filediver" -T unit', cwd=install).allowed
    assert guard.check_command("filediver -h", cwd=install).allowed
    assert guard.check_command("filediver-gui", cwd=ws).allowed


def test_extractors_that_write_next_to_their_input():
    from gst import config

    install = "C:/Program Files (x86)/Steam/steamapps/common/Some Game"
    out = f"{config.gs_home().as_posix()}/some-game/decomp/rpg"
    assert guard.check_command(f'unrpyc "{install}/game/script.rpyc"').rule == 5
    assert guard.check_command(f'unrpyc "{config.gs_home().as_posix()}/some-game/dumps/script.rpyc"').allowed
    assert guard.check_command(f'rvpacker-txt-rs json generate -i "{install}"').rule == 5
    assert guard.check_command(f'rvpacker-txt-rs json generate -i "{install}" -o "{out}"').allowed
    assert guard.check_command(f'rvpacker-txt-rs json generate -i "{install}" --output={out}').allowed
    assert guard.check_command(f'REE.Unpacker.exe RE4 "{install}/re_chunk_000.pak"').rule == 5
    assert guard.check_command(f'REE.Unpacker.exe RE4 "{install}/re_chunk_000.pak" "{out}"').allowed
    assert guard.check_command(f'UndertaleModCli dump "{install}/data.win" -o assets/gml',
                               cwd=config.gs_home() / "some-game").allowed  # relative output from the workspace


def test_pyinstaller_key_build_is_not_extracted(registry, tmp_path):
    game = tmp_path / "Packed Game"
    entry = {"install_dir": str(game), "verdict": policy.OFFLINE_OK,
             "protections": [f"encrypted-content:{policy.PYINSTALLER_KEY_ARCHIVE}"]}
    registry({"packed": entry})
    extract = f'pyinstxtractor-ng "{game / "Game.exe"}"'
    d = guard.check_command(extract)
    assert not d.allowed and d.rule == 4
    assert guard.check_command(f'pyinstxtractor-ng --info "{game / "Game.exe"}"').allowed  # the diagnosis writes nothing
    registry({"packed": {**entry, "protections": [{"kind": "encrypted-content", "name": policy.PYINSTALLER_KEY_ARCHIVE}]}})
    assert not guard.check_command(extract).allowed  # game.json keeps protections as objects
    registry({"packed": {**entry, "protections": []}})
    assert guard.check_command(extract).allowed


