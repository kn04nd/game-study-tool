def test_agent_write_scopes(tmp_path):
    ws = tmp_path / "ws"
    assert guard.check_write(ws / "notes" / "ai.md", "x", workspace=ws, agent_type="gst:code-navigator").allowed
    assert not guard.check_write(ws / "ARCHITECTURE.md", "x", workspace=ws, agent_type="gst:code-navigator").allowed
    assert guard.check_write(ws / "ARCHITECTURE.md", "x", workspace=ws, agent_type="gst:synthesizer").allowed
    assert not guard.check_write(ws / "notes" / "x.md", "x", workspace=ws, agent_type="gst:recon").allowed
    # unknown agents are not restricted by scope
    assert guard.check_write(ws / "anything.md", "x", workspace=ws, agent_type="general-purpose").allowed


