"""Path and command guards shared by gst and the plugin's PreToolUse hook.

Stdlib only and cheap: the hook runs on every Bash/PowerShell/Write/Edit call.
Patterns for derived output are adapted from universal-modder's um/publish.py (MIT).
"""

from __future__ import annotations

import os
import re
from functools import lru_cache
from pathlib import Path

from gst import policy
from gst.common import is_under, norm_path, read_json, write_json
from gst.policy import Decision

# Signals of derived game material for rule 7 (inside git work trees). The plugin hooks run in every
# session of every project, so only strong signals count: folder names like assets/, index/, dumps/
# or traces/ are everywhere in ordinary code and would block normal work.
DERIVED_DIRS = ("decomp",)
DERIVED_EXT = {
    ".uasset", ".uexp", ".ubulk", ".umap", ".pak", ".utoc", ".ucas",  # Unreal
    ".assets", ".ress", ".resource", ".bundle",                       # Unity (.resS lower-cased)
    ".pck", ".vpk", ".bsa", ".ba2", ".rpf",                           # Godot, Source, Creation, RAGE
    ".wem", ".bnk", ".fsb", ".bank",                                  # Wwise, FMOD
    ".dmp", ".run", ".rdc", ".pml", ".gzf", ".rcnet", ".ct",          # dumps, TTD, RenderDoc, Procmon, Ghidra, ReClass, CE
}
DECOMPILER_HEADERS = (
    "// Decompiled with ICSharpCode",
    "Decompiled with JetBrains decompiler",
    "// Source code recreated from a .class file",
    "Decompiled with CFR",
    "// Generated by Cpp2IL",
    "// Image 0: mscorlib.dll",
    "Generated by Il2CppInspector",  # its output header; the bare name also appears in docs about the tool
    "// Decompiled by",
)
_GHIDRA_ISMS = re.compile(r"\b(?:FUN|DAT|LAB|PTR|SUB)_[0-9a-fA-F]{6,}\b|\bundefined[1248]?\b|/\* WARNING: ")
_IL2CPP_RVA = re.compile(r"// RVA: 0x[0-9A-Fa-f]+")

STORE_ROOTS = (
    "C:/Program Files (x86)/Steam/steamapps/common",
    "C:/Program Files/Epic Games",
    "C:/Program Files (x86)/GOG Galaxy/Games",
    "C:/GOG Games",
    "C:/XboxGames",
)

# Where each plugin agent may write inside a workspace (relative paths; "" = workspace root file).
AGENT_WRITE_SCOPES: dict[str, tuple[str, ...]] = {
    "recon": (),
    "code-navigator": ("notes/", "FACTS.md", "STUDY.md"),
    "asset-analyst": ("assets/", "dumps/", "notes/", "FACTS.md", "STUDY.md"),
    "runtime-observer": ("traces/", "dumps/", "notes/", "FACTS.md", "STUDY.md"),
    "synthesizer": ("ARCHITECTURE.md", "notes/", "FACTS.md", "STUDY.md"),
    "mechanics-analyst": ("notes/", "FACTS.md", "STUDY.md"),
    "comparer": ("notes/", "STUDY.md"),
}


# --- git -----------------------------------------------------------------------------------

def git_root(path: str | os.PathLike) -> Path | None:
    """Nearest folder containing ``.git`` (dir or worktree file), walking up from ``path``."""
    p = Path(str(path))
    if not p.is_absolute():
        p = Path.cwd() / p
    folder = p if p.is_dir() else p.parent
    return _git_root_of(str(folder))


@lru_cache(maxsize=256)
def _git_root_of(folder: str) -> Path | None:
    current = Path(folder)
    for candidate in (current, *current.parents):
        try:
            if (candidate / ".git").exists():
                return candidate
        except OSError:
            return None
    return None


# --- content / path classification -----------------------------------------------------------

def looks_decompiled(text: str | None) -> bool:
    if not text:
        return False
    head = text[:4000]
    if any(marker in head for marker in DECOMPILER_HEADERS):
        return True
    sample = text[:200_000]
    return len(_GHIDRA_ISMS.findall(sample)) >= 5 or len(_IL2CPP_RVA.findall(sample)) >= 5


def has_derived_component(path: str | os.PathLike) -> bool:
    parts = norm_path(path).split("/")
    return any(part in DERIVED_DIRS for part in parts[:-1]) or Path(parts[-1]).suffix in DERIVED_EXT


@lru_cache(maxsize=1)
def steam_library_roots() -> tuple[str, ...]:
    """``steamapps/common`` folders of every Steam library (libraryfolders.vdf), cached per process."""
    candidates = []
    steam = _steam_path()
    if steam:
        vdf = Path(steam) / "steamapps" / "libraryfolders.vdf"
        try:
            text = vdf.read_text(encoding="utf-8", errors="replace")
            for match in re.finditer(r'"path"\s+"([^"]+)"', text):
                candidates.append(match.group(1).replace("\\\\", "\\"))
        except OSError:
            pass
        candidates.append(steam)
    roots = []
    for lib in candidates:
        common = Path(lib) / "steamapps" / "common"
        key = norm_path(common)
        if key not in roots:
            roots.append(key)
    return tuple(roots)


def _steam_path() -> str | None:
    if os.name != "nt":
        return None
    try:
        import winreg

        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Software\Valve\Steam") as key:
            value, _ = winreg.QueryValueEx(key, "SteamPath")
            return str(value)
    except OSError:
        default = Path("C:/Program Files (x86)/Steam")
        return str(default) if default.exists() else None


def registry_path() -> Path:
    from gst import config

    return config.gs_home() / "registry.json"


@lru_cache(maxsize=1)
def load_registry() -> dict:
    data = read_json(registry_path(), {})
    return data if isinstance(data, dict) else {}


def registry_games() -> dict[str, dict]:
    games = load_registry().get("games", {})
    return games if isinstance(games, dict) else {}


def save_registry_entry(slug: str, entry: dict) -> None:
    data = read_json(registry_path(), {}) or {}
    data.setdefault("games", {})[slug] = entry
    write_json(registry_path(), data)
    load_registry.cache_clear()


def install_roots() -> list[str]:
    roots = list(steam_library_roots()) + [norm_path(r) for r in STORE_ROOTS]
    roots += [norm_path(g["install_dir"]) for g in registry_games().values() if g.get("install_dir")]
    return roots


def is_game_install_path(path: str | os.PathLike) -> bool:
    return any(is_under(path, root) for root in install_roots())


def game_for_text(text: str) -> dict | None:
    """Registry game whose install dir or exe name appears in ``text``."""
    low = norm_path(text)
    words = set(re.findall(r"[\w.-]+\.exe\b", low))
    for slug, game in registry_games().items():
        install = game.get("install_dir")
        if install and norm_path(install) in low:
            return {"slug": slug, **game}
        exes = {e.lower() for e in game.get("exes", [])}
        if exes & words:
            return {"slug": slug, **game}
    return None


# --- decisions -----------------------------------------------------------------------------------

def check_write(
    path: str | os.PathLike,
    content: str | None = None,
    *,
    workspace: str | os.PathLike | None = None,
    agent_type: str | None = None,
) -> Decision:
    """May a file be written at ``path`` (Write/Edit tools, or gst itself)?"""
    if is_game_install_path(path):
        return Decision(False, f"{path} is inside a game install; the original install is read-only", 5)
    if content and os.path.basename(str(path)).lower() == ".mcp.json":
        from gst.mcp import audit_text

        problems = audit_text(content)
        if problems:
            return Decision(False, "; ".join(problems), 9)
    root = git_root(path)
    if root is not None and (has_derived_component(path) or looks_decompiled(content)):
        return Decision(False, f"derived game material must not be written inside the git work tree {root}", 7)
    if agent_type and workspace:
        agent = agent_type.rsplit(":", 1)[-1]
        if agent in AGENT_WRITE_SCOPES and is_under(path, workspace):
            rel = norm_path(path)[len(norm_path(workspace)) + 1 :]
            allowed = AGENT_WRITE_SCOPES[agent]
            if not any(rel == a.rstrip("/").lower() or rel.startswith(a.lower()) for a in allowed if a):
                scope = ", ".join(allowed) or "nothing (read-only agent)"
                return Decision(False, f"agent '{agent}' may only write: {scope}")
    return policy.ALLOW


# line continuations (Bash \, PowerShell `, cmd ^): the shell runs them as one line, so the rules see one line
_CONTINUATION = re.compile(r"[\\`^]\r?\n")
_GIT_MUTATING = re.compile(r"\bgit\b(?:\s+-C\s+(?P<c>\"[^\"]+\"|'[^']+'|\S+))?\s+(?P<verb>add|commit|init|stage)\b", re.IGNORECASE)
_REDIRECT = re.compile(r"(?:>>?|\|\s*(?:tee|out-file|set-content|add-content))\s*(?:-filepath\s+)?(?P<t>\"[^\"]+\"|'[^']+'|[^\s;|&]+)", re.IGNORECASE)
_CHDIR = re.compile(r"(?:^|[;&|(]\s*)(?:cd|chdir|pushd|set-location|sl)(?:\s+-(?:literal)?path)?\s+(?P<t>\"[^\"]+\"|'[^']+'|[^\s;|&]+)",
                    re.IGNORECASE)
# extractors that write into the current folder: RP6_UnpackCLI always, filediver without -o
_RP6 = re.compile(r"\brp6_unpackcli\b", re.IGNORECASE)
_FILEDIVER = re.compile(r"\bfilediver(?:\.exe)?(?![-\w])", re.IGNORECASE)
_OUTPUT_OR_HELP = re.compile(r"\s(?:-o|--output|-h|--help)\b", re.IGNORECASE)
# extractors that write next to their input unless given an output folder
_NEXT_TO_INPUT = re.compile(r"\b(?:unrpyc|ree\.unpacker|rvpacker[\w-]*|undertalemodcli)\b", re.IGNORECASE)
_OUTPUT_FLAG = re.compile(r"\s(?:-o|--output|-output)\b", re.IGNORECASE)


def _tokens(command: str) -> list[str]:
    import shlex

    try:
        return shlex.split(command, posix=False)
    except ValueError:
        return command.split()


# Plugin agents ignore permissionMode, so read-only agents are enforced here: each subcommand must
# start with one of these, without command substitution or redirection into files.
READ_ONLY_AGENTS = ("recon",)
_READ_ONLY_CMD = re.compile(
    r"(?:&\s*['\"][^'\"]*gst(?:\.exe)?['\"]|gst(?:\.exe)?)\s+(?:recon|status|doctor|guard|tools\s+(?:list|path|info)|config\s+show)\b"
    r"|(?:ls|dir|tree|cat|type|head|tail|wc|du|stat|file|rg|grep|findstr|find|diec|strings|cd|pwd|echo|"
    r"get-childitem|gci|get-content|gc|get-item|gi|select-string|sls|measure-object|select-object|sort-object|"
    r"where-object|format-list|format-table|test-path|resolve-path|set-location|get-location)(?![\w-])",
    re.IGNORECASE,
)
_SUBCOMMAND_SPLIT = re.compile(r"\|\||&&|[;|\n]")
_HARMLESS_REDIRECT = re.compile(r"\d?>>?\s*(?:&\d|/dev/null|\$null|nul)(?![\w/])", re.IGNORECASE)
_FIND_ACTIONS = re.compile(r"\bfind\b.*\s-(?:delete|exec|execdir|ok|okdir|fprint\w*|fls)\b", re.IGNORECASE)


def read_only_agent(agent_type: str | None) -> str | None:
    """The plugin agent name when ``agent_type`` is one of the read-only agents."""
    name = (agent_type or "").rsplit(":", 1)[-1]
    return name if name in READ_ONLY_AGENTS else None


def read_only_command(command: str) -> bool:
    if "$(" in command or "`" in command or _FIND_ACTIONS.search(command):
        return False
    if ">" in _HARMLESS_REDIRECT.sub("", command) or re.search(r"\b(?:out-file|set-content|add-content|tee)\b", command, re.I):
        return False
    parts = [p.strip() for p in _SUBCOMMAND_SPLIT.split(command)]
    return all(_READ_ONLY_CMD.match(p) for p in parts if p)


def check_command(command: str, *, cwd: str | os.PathLike | None = None, agent_type: str | None = None) -> Decision:
    """May a shell command (Bash or PowerShell) run? Returns the first violated rule."""
    if not command or not command.strip():
        return policy.ALLOW
    command = _CONTINUATION.sub(" ", command)
    rule = policy.deny_rule_for(command)
    if rule:
        return Decision(False, rule.reason, rule.rule)
    agent = read_only_agent(agent_type)
    if agent and not read_only_command(command):
        return Decision(False, f"the {agent} agent is read-only: gst recon/status/doctor/tools list and listing or "
                               "search commands (ls, rg, cat, Get-ChildItem...) without redirection")

    from gst import config

    for match in _GIT_MUTATING.finditer(command):
        home = config.gs_home()
        target = (match.group("c") or "").strip("\"'") or str(cwd or os.getcwd())
        if is_under(target, home):
            return Decision(False, f"no git {match.group('verb').lower()} inside the study root {home}", 7)
        after = command[match.end():]
        if match.group("verb").lower() in {"add", "stage"} and any(has_derived_component(t) for t in _tokens(after)):
            return Decision(False, "derived game material must not be staged in git", 7)

    for match in _REDIRECT.finditer(command):
        if is_game_install_path(match.group("t").strip("\"'")):
            return Decision(False, "commands must not write into a game install (read-only)", 5)

    low = command.lower()
    if re.search(r"\brepak(?:\.exe)?\s+unpack\b", low) and not re.search(r"\s(?:-o|--output)\b", low):
        return Decision(False, "repak unpack needs -o <workspace dir>; without it, it writes next to the pak inside the game", 5)
    if re.search(r"\bhgpaktool\b", low) and is_game_install_path_in(command):
        return Decision(False, "HGPAKtool extracts next to the input; copy the .pak into the workspace first", 5)
    if _RP6.search(command) or (_FILEDIVER.search(command) and not _OUTPUT_OR_HELP.search(command)):
        folders = [str(cwd or os.getcwd())] + [m.group("t").strip("\"'") for m in _CHDIR.finditer(command)]
        if any(is_game_install_path(f) for f in folders):
            return Decision(False, "this extractor writes into the current folder: run it from the workspace "
                                   "(filediver: or pass -o <workspace dir>), never from the game install", 5)
    if _NEXT_TO_INPUT.search(command) and is_game_install_path_in(command):
        home = config.gs_home()
        values = [t.strip("\"'").split("=", 1)[-1].strip("\"'") for t in _tokens(command)]
        explicit = any(is_under(v, home) for v in values if ":" in v or v.startswith("/"))
        relative = is_under(str(cwd or os.getcwd()), home) and _OUTPUT_FLAG.search(command)
        if not (explicit or relative):
            return Decision(False, "this tool writes next to its input: give it an output folder in the workspace "
                                   "(or copy the input there first), never the game install", 5)

    if policy.KEY_TOOLS.search(command) and policy.KEY_FLAGS.search(command):
        game = game_for_text(command) or _workspace_game(cwd)
        if not game or not policy.check(game, "decrypt").allowed:
            return Decision(False, "decryption keys are allowed only when game.json records a published key with its source URL", 4)
    if "pyinstxtractor" in low and "--info" not in low:
        game = game_for_text(command) or _workspace_game(cwd)
        prots = (game or {}).get("protections")
        names = [p if isinstance(p, str) else str(p.get("name", "")) if isinstance(p, dict) else str(p)
                 for p in (prots if isinstance(prots, list) else [])]
        if any(policy.PYINSTALLER_KEY_ARCHIVE in n for n in names):
            return Decision(False, "PyInstaller --key build: its key sits inside the exe and is not a published key; "
                                   "pyinstxtractor-ng would decrypt with it silently (only --info may run)", 4)

    if policy.RUNTIME_TOOLS.search(command):
        game = game_for_text(command)
        if game:
            decision = policy.check(game, "runtime")
            if not decision.allowed:
                return decision
        elif is_game_install_path_in(command):
            return Decision(False, "runtime tool aimed at a game that has no recon yet: run `gst recon <game>` first", 2, ask=True)
    return policy.ALLOW


def is_game_install_path_in(command: str) -> bool:
    for token in _tokens(command):
        token = token.strip("\"'")
        if (":" in token or token.startswith("/")) and is_game_install_path(token):
            return True
    return False


def _workspace_game(cwd: str | os.PathLike | None) -> dict | None:
    from gst import config

    ws = config.find_workspace(cwd)
    if not ws:
        return None
    data = read_json(ws / config.WORKSPACE_MARKER, {})
    return data if isinstance(data, dict) else None
